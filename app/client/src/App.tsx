const EMPTY_SET: Set<string> = new Set();

export default function App() {
  const reducedMotion = usePrefersReducedMotion();
  const phone = useIsPhone();

  // Step 1 filters. Keyword is debounced before it reaches the query parameters.
  const [issueCode, setIssueCode] = useState(DEFAULT_EXAMPLE.issue);
  const [keyword, setKeyword] = useState(DEFAULT_EXAMPLE.keyword);
  const [year, setYear] = useState(0);
  const debouncedKeyword = useDebounced(keyword, DEBOUNCE_MS);

  // Pick state. `selected` survives filter edits; `current` is null whenever the pick is not in the results.
  const [selected, setSelected] = useState<string | null>(null);
  const [highlighted, setHighlighted] = useState(-1);
  const [teamSize, setTeamSize] = useState<number | null>(null);
  const [idx, setIdx] = useState(LAST_IDX);
  const [viewed, setViewed] = useState<Set<string>>(EMPTY_SET);
  const [hasScrubbed, setHasScrubbed] = useState(false);
  const [justUnlocked, setJustUnlocked] = useState(false);
  const [runId, setRunId] = useState(0);

  const inputRef = useRef<HTMLInputElement | null>(null);
  const rowRefs = useRef<Map<string, HTMLElement>>(new Map());
  const step1Ref = useRef<HTMLDivElement | null>(null);
  const step2Ref = useRef<HTMLDivElement | null>(null);
  const step3Ref = useRef<HTMLDivElement | null>(null);

  // Step 1 query.
  const params = useMemo(
    () => ({
      issue_code: sql.string(issueCode),
      keyword: sql.string(debouncedKeyword),
      year: sql.int(year),
    }),
    [issueCode, debouncedKeyword, year]
  );
  const search = useBridgedQuery<SearchRow[]>();
  const { data, error } = search.state;
  const pending = isPending(search.state);
  const rows = useMemo(() => data ?? [], [data]);
  const current = useMemo(() => rows.find((r) => r.engagement_hk === selected) ?? null, [rows, selected]);
  const description = describeSearch(issueCode, debouncedKeyword, year);
  const firstIdx = current ? quarterIndexFor(current.first_period) : -1;

  // Three done flags, progress, current step.
  const done1 = rows.length > 0 && !pending;
  const done2 = current !== null && teamSize !== null;
  const done3 = current !== null && hasScrubbed;
  const done: [boolean, boolean, boolean] = useMemo(() => [done1, done2, done3], [done1, done2, done3]);
  const doneCount = Number(done1) + Number(done2) + Number(done3);
  const currentStep = !done1 ? 1 : !done2 ? 2 : !done3 ? 3 : 4;
  const complete = done1 && done2 && done3;
  const quarterLabel = QUARTER_LABELS[idx] ?? QUARTERS[idx] ?? '';
  const summary =
    complete && current
      ? `Answered for ${current.client}: ${rows.length} matching, ${teamSize ?? 0} on the team, viewed as of ${quarterLabel}.`
      : null;
  const nextExample = EXAMPLES.find((ex) => !(ex.issue === issueCode && ex.keyword === debouncedKeyword && year === 0));

  const state1: StepState = done1 ? 'done' : 'current';
  const state2: StepState = done2 ? 'done' : done1 ? 'current' : 'idle';
  const state3: StepState = done3 ? 'done' : done2 ? 'current' : 'idle';

  // Handlers.
  const clearSelection = useCallback(() => {
    setSelected(null);
    setTeamSize(null);
    setHasScrubbed(false);
    setViewed(EMPTY_SET);
    setJustUnlocked(false);
  }, []);

  const onFilters = useCallback((patch: Partial<Filters>) => {
    if (patch.issue !== undefined) setIssueCode(patch.issue);
    if (patch.keyword !== undefined) setKeyword(patch.keyword);
    if (patch.year !== undefined) setYear(patch.year);
    setHighlighted(-1);
  }, []);

  const onExample = useCallback(
    (ex: Example) => {
      onFilters({ issue: ex.issue, keyword: ex.keyword, year: 0 });
    },
    [onFilters]
  );

  const onClear = useCallback(() => onFilters({ issue: '', keyword: '', year: 0 }), [onFilters]);

  const pick = useCallback(
    (row: SearchRow) => {
      if (row.engagement_hk === selected) return;
      const last = quarterIndexFor(row.last_period);
      setSelected(row.engagement_hk);
      setTeamSize(null);
      setHasScrubbed(false);
      setViewed(EMPTY_SET);
      setIdx(last === -1 ? LAST_IDX : last);
      setJustUnlocked(true);
    },
    [selected]
  );

  useEffect(() => {
    if (!justUnlocked) return;
    const t = setTimeout(() => setJustUnlocked(false), UNLOCK_BADGE_MS);
    return () => clearTimeout(t);
  }, [justUnlocked]);

  const scrub = useCallback((next: number) => {
    const i = clamp(next, 0, LAST_IDX);
    const q = QUARTERS[i];
    setIdx(i);
    if (q) setViewed((prev) => (prev.has(q) ? prev : new Set(prev).add(q)));
    setHasScrubbed(true);
  }, []);

  const startOver = useCallback(() => {
    setIssueCode(DEFAULT_EXAMPLE.issue);
    setKeyword(DEFAULT_EXAMPLE.keyword);
    setYear(0);
    setHighlighted(-1);
    setIdx(LAST_IDX);
    clearSelection();
    setRunId((t) => t + 1);
    window.scrollTo({ top: 0, behavior: reducedMotion ? 'auto' : 'smooth' });
  }, [clearSelection, reducedMotion]);

  const jumpTo = useCallback(
    (step: number) => {
      const target = step === 1 ? step1Ref.current : step === 2 ? step2Ref.current : step3Ref.current;
      target?.scrollIntoView({ behavior: reducedMotion ? 'auto' : 'smooth', block: 'start' });
    },
    [reducedMotion]
  );

  /** A tap on a locked step moves the visitor to the action: Step 1 and its first Pick button. */
  const jumpToSearch = useCallback(() => {
    jumpTo(1);
    const first = rows[0];
    const el = first ? rowRefs.current.get(first.engagement_hk) : undefined;
    el?.querySelector('button')?.focus({ preventScroll: true });
  }, [jumpTo, rows]);

  // Keyboard: "/" search, Up/Down rows, Enter pick, Escape clear, "[" "]" quarter.
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.metaKey || e.ctrlKey || e.altKey) return;
      const t = e.target;
      const el = t instanceof HTMLElement ? t : null;
      if (
        el?.closest(
          'input, select, textarea, [contenteditable=""], [contenteditable="true"], [role="slider"], [role="combobox"]'
        )
      )
        return;
      if (
        document.querySelector('[role="dialog"][data-state="open"], [role="listbox"], [role="menu"][data-state="open"]')
      )
        return;
      const onControl = Boolean(el?.closest('button, a, [role="button"], tr[tabindex], li[tabindex]'));

      switch (e.key) {
        case '/':
          e.preventDefault();
          inputRef.current?.focus();
          inputRef.current?.select();
          break;
        case 'ArrowDown':
        case 'ArrowUp': {
          if (rows.length === 0) return;
          e.preventDefault();
          const delta = e.key === 'ArrowDown' ? 1 : -1;
          setHighlighted((h) => clamp(h + delta, 0, rows.length - 1));
          break;
        }
        case 'Enter': {
          if (onControl) return;
          const row = rows[highlighted];
          if (row) {
            e.preventDefault();
            pick(row);
          }
          break;
        }
        case 'Escape':
          if (selected) clearSelection();
          break;
        case '[':
        case ']':
          if (!current) return;
          e.preventDefault();
          scrub(idx + (e.key === ']' ? 1 : -1));
          break;
        default:
      }
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [rows, highlighted, selected, current, idx, pick, scrub, clearSelection]);

  // Keep focus and the highlight on the same row, and keep it in view.
  useEffect(() => {
    const hk = rows[highlighted]?.engagement_hk;
    if (!hk) return;
    const el = rowRefs.current.get(hk);
    if (!el) return;
    const active = document.activeElement;
    if (active !== el && !el.contains(active)) el.focus({ preventScroll: true });
    el.scrollIntoView({ block: 'nearest' });
  }, [rows, highlighted]);

  // Bring Step 2 into view after a pick.
  useEffect(() => {
    if (!selected) return;
    step2Ref.current?.scrollIntoView({ behavior: reducedMotion ? 'auto' : 'smooth', block: 'nearest' });
  }, [selected, reducedMotion]);

  const filters: Filters = { issue: issueCode, keyword, year };

  return (
    <TooltipProvider delayDuration={200}>
      {!search.draining && <SearchQuery key={search.epoch} params={params} onState={search.setState} />}
      <main className="mx-auto max-w-7xl space-y-8 px-4 pb-6 sm:px-6">
        <Header doneCount={doneCount} complete={complete} onReset={startOver} />

        <Tracker
          key={runId}
          done={done}
          currentStep={currentStep}
          clientName={current?.client ?? null}
          summary={summary}
          onJump={jumpTo}
          onJumpLocked={jumpToSearch}
        />

        <SearchCard
          filters={filters}
          onFilters={onFilters}
          onExample={onExample}
          onClear={onClear}
          onRetry={search.retry}
          inputRef={inputRef}
          rows={rows}
          pending={pending}
          error={error}
          current={current}
          highlighted={highlighted}
          onPick={pick}
          onHighlight={setHighlighted}
          rowRefs={rowRefs}
          description={description}
          sectionRef={step1Ref}
          state={state1}
          phone={phone}
        />

        <div className="grid gap-6 lg:grid-cols-2">
          <div ref={step2Ref} className="scroll-mt-28">
            {current ? (
              <TeamCard
                key={current.engagement_hk}
                current={current}
                state={state2}
                unlocked={justUnlocked}
                onResolved={setTeamSize}
                onJumpToSearch={jumpToSearch}
              />
            ) : (
              <LockedCard
                icon={Users}
                title="2. Who worked it?"
                description="Pick an engagement above to see everyone listed on its filings."
              />
            )}
          </div>
          <div ref={step3Ref} className="scroll-mt-28">
            {current ? (
              <AsOfCard
                key={current.engagement_hk}
                current={current}
                idx={idx}
                firstIdx={firstIdx}
                viewed={viewed}
                hasScrubbed={hasScrubbed}
                state={state3}
                unlocked={justUnlocked}
                onScrub={scrub}
              />
            ) : (
              <LockedCard
                icon={Clock}
                title="3. What did it look like at the time?"
                description="Pick an engagement above to rewind it to any quarter end."
              />
            )}
          </div>
        </div>

        {current && <BillsCard key={current.engagement_hk} current={current} />}

        {complete && current && (
          <CompletionCard
            current={current}
            matchCount={rows.length}
            teamSize={teamSize ?? 0}
            quarterLabel={quarterLabel}
            nextExample={nextExample}
            onReset={startOver}
            onExample={onExample}
          />
        )}

        <Footer />
      </main>
    </TooltipProvider>
  );
}
