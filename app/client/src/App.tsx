function useMediaQuery(query: string) {
  const subscribe = useCallback(
    (onChange: () => void) => {
      const mq = window.matchMedia(query);
      mq.addEventListener('change', onChange);
      return () => mq.removeEventListener('change', onChange);
    },
    [query]
  );
  return useSyncExternalStore(
    subscribe,
    () => window.matchMedia(query).matches,
    () => false
  );
}
const usePrefersReducedMotion = () => useMediaQuery('(prefers-reduced-motion: reduce)');
const useIsPhone = () => useMediaQuery('(max-width: 767px)');

/** Animates from the value on screen to `target` on requestAnimationFrame; instant under reduced motion. */
function useCountUp(target: number, duration = COUNT_UP_MS) {
  const reduced = usePrefersReducedMotion();
  const [value, setValue] = useState(target);
  const fromRef = useRef(target);
  const shownRef = useRef(target);
  useEffect(() => {
    if (reduced) {
      shownRef.current = target;
      fromRef.current = target;
      return;
    }
    const from = fromRef.current;
    if (from === target) return;
    let raf = 0;
    let start = 0;
    const tick = (now: number) => {
      if (start === 0) start = now;
      const t = Math.min(1, (now - start) / duration);
      const eased = 1 - Math.pow(1 - t, 3);
      const next = Math.round(from + (target - from) * eased);
      shownRef.current = next;
      setValue(next);
      if (t < 1) raf = requestAnimationFrame(tick);
      else fromRef.current = target;
    };
    raf = requestAnimationFrame(tick);
    return () => {
      cancelAnimationFrame(raf);
      fromRef.current = shownRef.current;
    };
  }, [target, duration, reduced]);
  return reduced ? target : value;
}

function useDebounced<T>(value: T, ms: number) {
  const [debounced, setDebounced] = useState(value);
  useEffect(() => {
    const t = setTimeout(() => setDebounced(value), ms);
    return () => clearTimeout(t);
  }, [value, ms]);
  return debounced;
}

/**
 * Holds a query's result outside the hook that fetches it. The fetching hook lives in a small
 * bridge component, so "Try again" can unmount the bridge for one macrotask (which lets the shared
 * request store drop the failed entry) and mount it again for a clean re-run with identical parameters.
 */
function useBridgedQuery<T>() {
  const [state, setState] = useState<QueryState<T>>({ data: null, loading: true, error: null });
  const [epoch, setEpoch] = useState(0);
  const [draining, setDraining] = useState(false);
  const retry = useCallback(() => {
    setState({ data: null, loading: true, error: null });
    setDraining(true);
  }, []);
  useEffect(() => {
    if (!draining) return;
    const t = setTimeout(() => {
      setEpoch((e) => e + 1);
      setDraining(false);
    }, 0);
    return () => clearTimeout(t);
  }, [draining]);
  return { state, setState, epoch, draining, retry };
}

