/** Enter or Space on the row itself picks it; keys fired on a control inside the row are left to that control. */
function rowKeyHandler<E extends HTMLElement>(pick: () => void) {
  return (e: ReactKeyboardEvent<E>) => {
    if (e.target !== e.currentTarget) return;
    if (e.key === 'Enter' || e.key === ' ') {
      e.preventDefault();
      pick();
    }
  };
}

